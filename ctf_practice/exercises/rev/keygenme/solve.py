import hashlib

s = bytes([
    0x61, 0x63, 0x61, 0x64, 0x65, 0x6d, 0x79, 0x7b,
    0x62, 0x72, 0x31, 0x6e, 0x67, 0x5f, 0x79, 0x30,
    0x75, 0x72, 0x5f, 0x30, 0x77, 0x6e, 0x5f, 0x6b,
    0x33, 0x79, 0x5f,
])
assert len(s) == 27
digest = hashlib.md5(s).hexdigest()
idxs = [21, 21, 0, 15, 5, 11, 8, 8]
suffix = "".join(digest[i] for i in idxs) + "}"
key = s.decode() + suffix
print(digest)
print(key)
print(len(key))
